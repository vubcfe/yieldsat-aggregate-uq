#!/usr/bin/env python3
"""Paper tables from results/<exp>/seed_*.json (written by scripts/export_results.py).
Each cell is the mean over seeds; tables go to outputs/tables/tab_<name>.tex. Do not edit by hand.
"""
import glob, json, os
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, "outputs", "tables")
PAIRS = ["AR-corn", "AR-soybean", "AR-wheat", "BR-corn", "BR-soybean", "BR-wheat", "DE-rapeseed", "DE-wheat",
         "UY-soybean"]
LABEL = {p: p.replace("AR", "Argentina").replace("BR", "Brazil").replace("DE", "Germany").replace("UY", "Uruguay")
         .replace("-", " ") for p in PAIRS}


def load(exp):
    recs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(ROOT, "results", exp, "seed_*.json")))]
    out = defaultdict(lambda: defaultdict(list))
    for r in recs:
        for m, ms in r["metrics"].items():
            for k, v in ms.items():
                out[m][k].append(v)
    return out, len(recs)


def cell(R, m, k, d=2, pct=False, sd=False):
    v = R.get(m, {}).get(k)
    if not v:
        return "--"
    x = np.mean(v) * (100 if pct else 1)
    s = f"{x:.{0 if pct else d}f}".replace("-", "$-$")
    if sd and len(v) > 1:
        s += f"\\,{{\\scriptsize$\\pm${np.std(v, ddof=1) * (100 if pct else 1):.{0 if pct else d}f}}}"
    return s


def save(name, lines):
    os.makedirs(GEN, exist_ok=True)
    open(os.path.join(GEN, f"tab_{name}.tex"), "w").write(
        "% Generated by analysis/make_tables.py from results/. Do not edit by hand.\n" + "\n".join(lines) + "\n")


def t_e1():
    R, n = load("e1")
    if not n:
        return
    L = [r"\begin{tabular}{l ccc ccc ccc}", r"\toprule",
         r" & \multicolumn{3}{c}{Pixel $R^2$} & \multicolumn{3}{c}{Within-field $R^2_w$} & \multicolumn{3}{c}{Field $R^2_F$} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}",
         r"Country, crop & ID & Phys. & Block & ID & Phys. & Block & ID & Phys. & Block \\", r"\midrule"]
    for p in PAIRS:
        row = [LABEL[p]]
        for k in ("r2_pixel", "r2_within", "r2_field"):
            row += [cell(R, f"{p}_{s}", k) for s in ("field", "physical_field", "block")]
        L.append(" & ".join(row) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    save("e1", L)


E2M = [("L0_B0", "P", "B0"), ("L1_B1", "P", "B1"), ("L1_B2", "P", "B2"), ("L1_B2pv", "P", "B2pv"),
       ("L1_B8", "P", "B8"), ("L1_B8pv", "P", "B8pv"), ("L1_B11", "P", "B11"), ("L1_B6", "D", "B6")]


def t_e2():
    R, n = load("e2")
    if not n:
        return
    f = os.path.join(ROOT, "results", "e2ci", "seed_0.json")
    CI = json.load(open(f))["metrics"] if os.path.exists(f) else {}
    for metric, name in (("r2_within", "e2_within"), ("rho_within", "e2_rho")):
        L = [r"\begin{tabular}{l" + "c" * len(E2M) + "}", r"\toprule",
             "Country, crop & " + " & ".join(f"{lab}" for _, _, lab in E2M) + r" \\", r"\midrule"]
        for p in PAIRS + ["MEAN5", "MEAN9"]:
            lab = {"MEAN5": r"Mean, 5 pairs$^a$", "MEAN9": "Mean, 9 pairs"}.get(p, LABEL.get(p))
            if p == "MEAN5":
                L.append(r"\midrule")
            L.append(" & ".join([lab] + [cell(R, f"{p}_{mode}_{k}", metric) for k, mode, _ in E2M]) + r" \\")
            if p.startswith("MEAN") and metric == "r2_within" and CI:
                ci = []
                for k, mode, _ in E2M:
                    v = CI.get(f"{p}_{'B0' if k == 'L0_B0' else k}")
                    ci.append(r"\scriptsize[" + f"{v['lo']:.2f}, {v['hi']:.2f}]".replace("-", "$-$") if v and mode == "P" else "")
                L.append(" & ".join([r"\quad\scriptsize 95\,\% CI"] + ci) + r" \\")
        L += [r"\bottomrule", r"\end{tabular}"]
        save(name, L)
    # levels x methods, mean over the 5 pairs with a usable ceiling
    levels = [("L1", "Field"), ("L2", "Farm-year"), ("L3_20", "20 km cell"), ("L3_50", "50 km cell"),
              ("Lrand", "Random")]
    meths = ["B1", "B2", "B2pv", "B8", "B11"]
    for agg, nm in (("MEAN5", "e2_levels"), ("MEAN9", "e2_levels9")):
        L = [r"\begin{tabular}{l" + "c" * (len(meths) + 1) + "}", r"\toprule",
             "Bag level & " + " & ".join(meths) + r" & B6 (D) \\", r"\midrule"]
        for lv, lab in levels:
            row = [lab] + [cell(R, f"{agg}_P_{lv}_{m}", "r2_within") for m in meths]
            row.append(cell(R, f"{agg}_D_{lv}_B6", "r2_within") if lv != "Lrand" else "--")
            L.append(" & ".join(row) + r" \\")
        L += [r"\bottomrule", r"\end{tabular}"]
        save(nm, L)
    # mode D at coarse levels: field-level skill from a farm-year or regional aggregate
    L = [r"\begin{tabular}{l ccc ccc}", r"\toprule",
         r" & \multicolumn{3}{c}{Field $R^2_F$} & \multicolumn{3}{c}{Pixel $R^2$} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}",
         r"Known aggregate & Flat & B11 & B0 & Flat & B11 & B0 \\", r"\midrule"]
    L.append(" & ".join(["None (mode P)", "--", cell(R, "MEAN9_P_L1_B11", "r2_field"), cell(R, "MEAN9_P_L0_B0", "r2_field"),
                         "--", cell(R, "MEAN9_P_L1_B11", "r2_pixel"), cell(R, "MEAN9_P_L0_B0", "r2_pixel")]) + r" \\")
    for lv, lab in levels[:-1]:
        row = [lab]
        for k in ("r2_field", "r2_pixel"):
            row += [cell(R, f"MEAN9_D_{lv}_{m}", k) for m in ("FLAT", "B11", "B0")]
        L.append(" & ".join(row) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    save("e2_modeD", L)


